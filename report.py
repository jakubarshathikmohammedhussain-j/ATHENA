def tiles(items):
    cells = "".join(
        f"<td width='33%' valign='top' style='padding:0 4px'><div style='background:#f6f7fa;border-radius:14px;padding:14px'>"
        f"<div style='font-size:22px;font-weight:700;letter-spacing:-.01em'>{e(v)}</div>"
        f"<div style='font-size:12px;color:{MUTED}'>{e(label)}</div></div></td>" for v, label in items)
    return f"<table role='presentation' width='100%' cellpadding='0' cellspacing='0' style='margin:8px 0 14px'><tr>{cells}</tr></table>"


