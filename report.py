def safe(u):
    return u if str(u).startswith(("http://", "https://")) else ""


def fmt_metrics(m):
    out, cur = [], (m.get("currency") or "").strip()
    v = m.get("market_cap")
    if v:
        out.append(("Market cap", f"{cur} {v / 1e12:.2f}T".strip() if v >= 1e12 else f"{cur} {v / 1e9:.1f}B".strip()))
    if m.get("revenue_growth") is not None:
        out.append(("Revenue growth", f"{m['revenue_growth'] * 100:+.1f}%"))
    if m.get("operating_margin") is not None:
        out.append(("Operating margin", f"{m['operating_margin'] * 100:.1f}%"))
    if m.get("pe"):
        out.append(("P/E ratio", f"{m['pe']:.1f}"))
    return out


def items_html(items, smap):
    if not items:
        return f"<p style='color:{MUTED}'>Not enough sourced data to say.</p>"
    rows = []
    for it in items:
        ev = it.get("type") == "evidence"
        label = "Evidence" if ev else f"Inference · {it.get('confidence') or 'medium'}"
        color = INK if ev else BLUE
        refs = []
        for s in it.get("sources", []):
            u = smap.get(s)
            refs.append(f"<a href='{e(u)}' style='color:{MUTED}'>[{e(s)}]</a>" if u else f"[{e(s)}]")
        rows.append(
            f"<li style='margin:8px 0'><b style='font-size:12px;color:{color}'>{label}</b> {e(it.get('text', ''))} "
            f"<span style='color:{MUTED};font-size:12px'>{' '.join(refs)}</span></li>")
    return "<ul style='padding-left:18px;margin:6px 0'>" + "".join(rows) + "</ul>"


def h3(t):
    return f"<h3 style='font-size:13px;color:{MUTED};margin:18px 0 4px'>{e(t)}</h3>"


def changes(prev, cur):
    if not prev:
        return ["First brief for this company. Changes will show from the next one."]
    old = {s["title"] for s in prev.get("sources", [])}
    out = ["New headline: " + s["title"] for s in cur["sources"] if s.get("kind") == "news" and s["title"] not in old][:5]
    a, b = (prev.get("metrics") or {}).get("market_cap"), (cur.get("metrics") or {}).get("market_cap")
    if a and b:
        out.append(f"Market cap {'up' if b > a else 'down'} {abs(b / a - 1) * 100:.1f}% since the last brief.")
    return out or ["No notable changes since the last brief."]


def company_html(d, chg=None):
    smap = {s["id"]: safe(s.get("url", "")) for s in d["sources"]}
    nums = "".join(
        f"<td style='padding:8px 18px 8px 0'><div style='font-size:20px;font-weight:600'>{e(v)}</div>"
        f"<div style='font-size:12px;color:{MUTED}'>{e(k)}</div></td>" for k, v in fmt_metrics(d.get("metrics") or {}))
    tick = f" · {e(d['ticker'])}" if d.get("ticker") else ""
    chg_html = h3("What changed") + "<ul style='padding-left:18px;margin:6px 0'>" + "".join(
        f"<li style='margin:6px 0'>{e(c)}</li>" for c in chg) + "</ul>" if chg else ""
    return (
        f"<h2 style='font-size:24px;margin:30px 0 4px'>{e(d['company'])}{tick}</h2>"
        f"<p style='font-size:16px;color:{MUTED};margin:0 0 10px'>{e(d.get('headline', ''))}</p>"
        f"<table><tr>{nums}</tr></table>{chg_html}"
        + h3("Executive pulse") + items_html(d["pulse"], smap)
        + h3("Hidden operational risks") + items_html(d["risks"], smap)
        + h3("Strategic opportunities") + items_html(d["opportunities"], smap))


