BAND = {"Low": "#1d7f3a", "Medium": "#b26a00", "High": "#c4310e", "Severe": "#8b0000", "Unknown": MUTED}


def radar_changes(prev, cur):
    if not prev:
        return ["First radar run. Changes will show from the next one."]
    old = {s["name"]: s["band"] for s in prev.get("suppliers", [])}
    out = [f"{s['name']} moved from {old[s['name']]} to {s['band']}." for s in cur["suppliers"]
           if s["name"] in old and old[s["name"]] != s["band"]]
    return out or ["No supplier changed risk level since the last run."]


def radar_html(res, chg=None):
    s = res["summary"]
    exp = f" Spend exposed to high risk: {s['exposed_spend']:,.0f} ({s['exposed_pct']:.0f}%)." if s["total_spend"] else ""
    rows = []
    for x in res["suppliers"]:
        col = BAND.get(x["band"], MUTED)
        score = "n/a" if x["score"] is None else str(x["score"])
        bar = f"<div style='background:#e8e8ed;border-radius:4px;height:8px'><div style='background:{col};width:{x['score'] or 0}%;height:8px;border-radius:4px'></div></div>"
        drv = "".join(
            f"<li style='margin:4px 0'>{e(d['text'])} <span style='color:{MUTED};font-size:12px'>"
            + (f"<a href='{e(safe(d['url']))}' style='color:{MUTED}'>{e(d['source'])}</a>" if d.get("url") and safe(d["url"]) else e(d["source"]))
            + "</span></li>" for d in x["drivers"])
        act = "".join(f"<li style='margin:4px 0'>{e(a)}</li>" for a in x["actions"])
        rows.append(
            f"<div style='padding:14px 0;border-top:1px solid #d2d2d7'><div><b>{e(x['name'])}</b> "
            f"<span style='color:{MUTED};font-size:13px'>{e(x['place'] or x['location'])}</span> "
            f"<b style='color:{col};float:right'>{e(x['band'])} · {score}</b></div>{bar}"
            + (f"<p style='color:{MUTED};font-size:13px'>{e(x['note'])}</p>" if x.get("note") else "")
            + (f"<ul style='padding-left:18px;margin:8px 0'>{drv}</ul>" if drv else "")
            + (f"<div style='font-size:12px;color:{MUTED}'>Suggested actions (Athena's inference)</div><ul style='padding-left:18px;margin:4px 0'>{act}</ul>" if act else "")
            + "</div>")
    ch = (h3("What changed") + "<ul style='padding-left:18px'>" + "".join(f"<li>{e(c)}</li>" for c in chg) + "</ul>") if chg else ""
    return (f"<h2 style='font-size:24px;margin:26px 0 4px'>Supplier risk radar</h2>"
            f"<p style='color:{MUTED};margin:0 0 8px'>{s['high_count']} of {s['count']} suppliers at high risk this week.{e(exp)}</p>{ch}{''.join(rows)}"
            f"<p style='font-size:12px;color:{MUTED}'>Scores combine a 7-day weather forecast with recent news headlines. They flag risk to check, not a prediction.</p>")


def radar_email(res, chg, link, unsub_url):
    body = radar_html(res, chg) + f"<p><a href='{e(link)}' style='color:{BLUE}'>Open or download as PDF</a></p>"
    return shell("Your supplier risk radar", body, f"{DISCLAIMER} <a href='{e(unsub_url)}'>Unsubscribe</a>")


def radar_page(res):
    body = radar_html(res) + "<p class='np'><button onclick='window.print()' style='font:500 15px sans-serif;padding:10px 18px;border:1px solid #0071e3;color:#0071e3;background:#fff;border-radius:99px'>Download as PDF</button></p>"
    return shell("Supplier risk radar", body, DISCLAIMER)
